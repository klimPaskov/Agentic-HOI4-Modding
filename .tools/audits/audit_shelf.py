#!/usr/bin/env python3
"""Drift checks for the vanilla reference shelf and for the hoi4-imagegen family list.

The shelf (`.claude/skills/hoi4-feature-assets/assets/vanilla_reference/`) is built from an installed game by
`.tools/gfx/shelf/build_shelf.py`, which writes `.tools/gfx/shelf/catalog.json`. `CATALOG.md` and
`REFERENCE_MANIFEST.md` in the shelf are rendered from that catalog and `kept_inputs.json`. Rules, all `error`
level under the `.tools/lib/report.py` contract:

- `SHELF-MISSING`: a PNG listed in the catalog or in `kept_inputs.json` is not in the shelf.
- `SHELF-HASH`: a PNG's SHA-256 differs from the catalog.
- `SHELF-EXTRA`: a file in the shelf that the catalog and `kept_inputs.json` do not list (contact sheets and the
  three documents excepted).
- `SHELF-COUNT`: a family's catalog count differs from its selection, or a folder holds another number of PNGs.
- `SHELF-CONTACT-SHEET`: a family folder has no `contact_sheet.png`.
- `SHELF-DOC-STALE`: `CATALOG.md` or `REFERENCE_MANIFEST.md` differs from what the catalog renders to.
- `SHELF-DOC-FOLDER`: `README.md`, `CATALOG.md` or `interface/README.md` names a shelf folder that does not exist.
- `FAMILY-IDS`: the family ids of `profiles.json`, of the catalog or of the builder input are not exactly the
  40 ids in `.tools/gfx/family_ids.json`, or `profiles.json` has a row that is not one of them.

`--write-docs` rewrites the two documents from the catalog. The check needs no installed game. A mod that does
not carry `.tools/gfx/shelf/catalog.json` has nothing to check.

Usage:
	python -B .tools/audits/audit_shelf.py
	python -B .tools/audits/audit_shelf.py --write-docs
	python -B .tools/audits/audit_shelf.py --json .tmp/shelf.json

Exit status: 0 no errors, 1 errors.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Set, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # .tools, for the shared lib package
from lib.report import Finding, PathFilter, add_arguments, exit_code, merge_json, print_findings, requested_paths

REPO_ROOT = Path(__file__).resolve().parents[2]
CHECK = "shelf"
LEVELS = {
	"SHELF-MISSING": "error", "SHELF-HASH": "error", "SHELF-EXTRA": "error", "SHELF-COUNT": "error",
	"SHELF-CONTACT-SHEET": "error", "SHELF-DOC-STALE": "error", "SHELF-DOC-FOLDER": "error", "FAMILY-IDS": "error",
}
SHELF_DIR = ".claude/skills/hoi4-feature-assets/assets/vanilla_reference"
CATALOG_FILE = ".tools/gfx/shelf/catalog.json"
KEPT_FILE = ".tools/gfx/shelf/kept_inputs.json"
BUILDER_INPUT = ".tools/gfx/shelf/families.json"
FAMILY_IDS_FILE = ".tools/gfx/family_ids.json"
PROFILES_FILE = ".tools/gfx/profiles.json"
DOCUMENTS = ("CATALOG.md", "REFERENCE_MANIFEST.md")
CONTACT_SHEET = "contact_sheet.png"
GAME_FILES = (".gfx", ".gui", ".asset", ".mesh", ".txt")
SHELF_ROOTS = ("event_art", "flags", "icons", "portraits", "units", "interface")
FOLDER_MENTION = re.compile(r"`((?:" + "|".join(SHELF_ROOTS) + r")/[A-Za-z0-9_./-]*?)/?`")


def read_json(path: Path) -> Dict[str, Any]:
	data = json.loads(path.read_text(encoding="utf-8"))
	return data if isinstance(data, dict) else {}


def sha256(path: Path) -> str:
	return hashlib.sha256(path.read_bytes()).hexdigest()


def read_text(path: Path) -> str:
	return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def family_path(family: Dict[str, Any], selected: Dict[str, Any]) -> str:
	"""Shelf-relative path of one selected file (flag entries already carry their size folder)."""
	return f"{family['shelf_folder']}/{selected['file']}"


# ---------------------------------------------------------------------------
# Rendering of CATALOG.md and REFERENCE_MANIFEST.md
# ---------------------------------------------------------------------------

def cell(text: object) -> str:
	return str(text).replace("|", "\\|").replace("\n", " ")


def render_catalog(catalog: Dict[str, Any], kept: Dict[str, Any]) -> str:
	families: List[Dict[str, Any]] = catalog["families"]
	lines = [
		"# Canonical asset-reference catalog",
		"",
		f"Built from the installed game {catalog['game_version']} (raw version {catalog['game_raw_version']}). Generated by `.tools/audits/audit_shelf.py --write-docs` from `.tools/gfx/shelf/catalog.json`; do not edit by hand.",
		"",
		"The PNGs are lossless RGBA decodes of vanilla textures at their native size. They are review and style references for the asset families of `hoi4-imagegen`. Never wire, ship, trace, recolour or copy them into final art, and do not infer a redistribution licence from their presence. Every family folder has a labelled `contact_sheet.png`.",
		"",
		"## How the shelf is chosen",
		"",
		"Each family lists the vanilla textures of its folders (base game and every DLC, a later root overriding the same path), drops undecodable, empty, uniform, placeholder and duplicate images, describes every image with 19 colour, edge and alpha numbers, and keeps the k-medoids of those descriptors, spread over base game and DLC and capped per nation. Same game files, same `families.json` and the same seed give the same shelf. Rebuild it after a game update:",
		"",
		"```powershell",
		"python .tools/gfx/shelf/build_shelf.py --game \"<HOI4 install folder>\" --out <empty folder> --families-json .tools/gfx/shelf/families.json",
		"```",
		"",
		"Copy the result's `vanilla_reference/` over the shelf, copy its `catalog.json` to `.tools/gfx/shelf/catalog.json`, then run `python .tools/audits/audit_shelf.py --write-docs`. `REFERENCE_MANIFEST.md` lists every file with its source texture and both SHA-256 values.",
		"",
		"## Coverage",
		"",
		"| Family | Shelf folder | Canvas | Registered frames (frames: files) | Files | Candidates | Contact sheet |",
		"| --- | --- | --- | --- | ---: | ---: | --- |",
	]
	for family in families:
		frames = ", ".join(f"{name}: {count}" for name, count in sorted(family["frames"].items()))
		sheet = f"{family['shelf_folder']}/{CONTACT_SHEET}"
		lines.append(f"| `{family['id']}` | `{family['shelf_folder']}` | {family['dominant_canvas']} | {frames} | {family['selected_count']} | {family['candidate_count']} | `{sheet}` |")
	lines += [
		"",
		"`flags` holds one set of tags at the three sizes (`flags/normal`, `flags/medium`, `flags/small`). `counter_small` is split over three folders because land, air and naval counters differ (`counter_small_air` and `counter_small_naval` are sub-shelves of the `counter_small` family). Families whose canvas the game does not fix have no shelf: `gui_texture` follows the windows in `interface/vanilla`, and `super_event` is a mod pattern with no vanilla texture. Missions use the decision icons, so there is no mission folder.",
		"",
		"## Tool and pipeline inputs",
		"",
		"These files are not vanilla family references. They are inputs of the kit's asset tools and the 3D and GUI review folders, and are never replaced when the shelf is rebuilt.",
		"",
		"| Folder | Files | Purpose |",
		"| --- | ---: | --- |",
	]
	for group in kept["groups"]:
		lines.append(f"| `{group['folder']}` | {len(group['files'])} | {cell(group['purpose'])} |")
	notes = [(family["id"], family["notes"]) for family in families if family.get("notes")]
	lines += ["", "## Family notes", ""]
	lines += [f"- `{name}`: {note}" for name, note in notes]
	return "\n".join(lines) + "\n"


def manifest_rows(family: Dict[str, Any]) -> List[str]:
	rows = []
	for item in family["selected"]:
		frames = "/".join(item["frames"])
		sprites = ", ".join(f"`{name}`" for name in item["sprites"][:2]) or "none"
		rows.append(
			f"| `{family_path(family, item)}` | {item['width']}x{item['height']} | {frames} | `{item['source_path']}` | {item['source_root']} | {sprites} | "
			f"`{item['source_sha256']}` | `{item['png_sha256']}` |")
	return rows


def render_manifest(catalog: Dict[str, Any], kept: Dict[str, Any]) -> str:
	lines = [
		"# Vanilla reference manifest",
		"",
		"Generated by `.tools/audits/audit_shelf.py --write-docs` from `.tools/gfx/shelf/catalog.json`; do not edit by hand. `python .tools/audits/audit_shelf.py` fails when a PNG, a family folder or this file drifts from the catalog.",
		"",
		f"- Game: {catalog['game_version']} (raw version {catalog['game_raw_version']}), executable modified {catalog['hoi4_exe_mtime']}",
		f"- Source roots: {', '.join(f'`{root}`' for root in catalog['roots'])}",
		f"- Built: {catalog['generated']} with seed {catalog['seed']}; Python {catalog['tool_versions']['python']}, Pillow {catalog['tool_versions']['pillow']}, NumPy {catalog['tool_versions']['numpy']}",
		"",
		"## Method",
		"",
		"```text",
		str(catalog["method"]).strip("\n"),
		"```",
		"",
		"The review files are lossless RGBA PNG decodes (file name = texture stem) and are not runtime assets. Frame counts come from the owning sprite definition; `unregistered` means no sprite registers the texture. The two SHA-256 columns are the source texture and the shelf PNG.",
	]
	for family in catalog["families"]:
		skipped = sum(int(entry["count"]) for entry in family.get("skipped", {}).values())
		lines += [
			"",
			f"## `{family['id']}`",
			"",
			f"Folder `{family['shelf_folder']}`, canvas {family['dominant_canvas']}, {family['selected_count']} files selected from {family['candidate_count']} candidates ({skipped} skipped). Sources: {', '.join(f'`{d}`' for d in family['source_dirs'])}.",
			"",
			"| Review PNG | Size | Frames | Source texture | Root | Sprites | Source SHA-256 | PNG SHA-256 |",
			"| --- | --- | --- | --- | --- | --- | --- | --- |",
		]
		lines += manifest_rows(family)
	lines += ["", "## Tool and pipeline inputs", "", "| File | SHA-256 |", "| --- | --- |"]
	for group in kept["groups"]:
		lines += [f"| `{path}` | `{digest}` |" for path, digest in group["files"].items()]
	return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------

def shelf_files(shelf: Path) -> Set[str]:
	return {path.relative_to(shelf).as_posix() for path in shelf.rglob("*") if path.is_file()}


def finding(rule: str, path: str, message: str) -> Finding:
	return Finding(CHECK, rule, LEVELS[rule], path, 0, message)


def check_files(shelf: Path, catalog: Dict[str, Any], kept: Dict[str, Any]) -> List[Finding]:
	found: List[Finding] = []
	expected: Dict[str, str] = {}
	for family in catalog["families"]:
		for item in family["selected"]:
			expected[family_path(family, item)] = item["png_sha256"]
	for group in kept["groups"]:
		expected.update(group["files"])
	present = shelf_files(shelf)
	for path, digest in sorted(expected.items()):
		if path not in present:
			found.append(finding("SHELF-MISSING", f"{SHELF_DIR}/{path}", "listed in the shelf catalog but not in the shelf"))
		elif sha256(shelf / path) != digest:
			found.append(finding("SHELF-HASH", f"{SHELF_DIR}/{path}", "SHA-256 differs from the shelf catalog; rebuild the shelf instead of editing a reference"))
	allowed = set(expected) | set(DOCUMENTS) | {"README.md", "interface/README.md"}
	for path in sorted(present - allowed):
		if not path.endswith(CONTACT_SHEET):
			found.append(finding("SHELF-EXTRA", f"{SHELF_DIR}/{path}", "not listed in the shelf catalog or in kept_inputs.json"))
	return found


def check_counts(shelf: Path, catalog: Dict[str, Any], kept: Dict[str, Any]) -> List[Finding]:
	found: List[Finding] = []
	folders: Dict[str, int] = {}
	for family in catalog["families"]:
		tags = {item["file"].rsplit("/", 1)[-1] for item in family["selected"]}  # a flag is one tag at three sizes
		if len(tags) != family["selected_count"]:
			found.append(finding("SHELF-COUNT", CATALOG_FILE, f"{family['id']} lists {len(tags)} files but selected_count is {family['selected_count']}"))
		for item in family["selected"]:
			folder = family_path(family, item).rsplit("/", 1)[0]
			folders[folder] = folders.get(folder, 0) + 1
	kept_files = {path for group in kept["groups"] for path in group["files"]}
	for folder, count in sorted(folders.items()):
		directory = shelf / folder
		pngs = [path for path in directory.glob("*.png") if path.name != CONTACT_SHEET and f"{folder}/{path.name}" not in kept_files] if directory.is_dir() else []
		if len(pngs) != count:
			found.append(finding("SHELF-COUNT", f"{SHELF_DIR}/{folder}", f"catalog lists {count} PNGs, the folder holds {len(pngs)}"))
		if directory.is_dir() and not (directory / CONTACT_SHEET).is_file():
			found.append(finding("SHELF-CONTACT-SHEET", f"{SHELF_DIR}/{folder}", "family folder has no contact_sheet.png"))
	return found


def check_documents(shelf: Path, catalog: Dict[str, Any], kept: Dict[str, Any]) -> List[Finding]:
	found: List[Finding] = []
	rendered = {"CATALOG.md": render_catalog(catalog, kept), "REFERENCE_MANIFEST.md": render_manifest(catalog, kept)}
	for name, text in rendered.items():
		path = shelf / name
		if not path.is_file() or read_text(path) != text:
			found.append(finding("SHELF-DOC-STALE", f"{SHELF_DIR}/{name}", "differs from the catalog; run `python .tools/audits/audit_shelf.py --write-docs`"))
	return found


def check_doc_folders(shelf: Path) -> List[Finding]:
	found: List[Finding] = []
	for name in ("README.md", "CATALOG.md", "interface/README.md"):
		path = shelf / name
		if not path.is_file():
			continue
		for mention in sorted(set(FOLDER_MENTION.findall(read_text(path)))):
			if mention.endswith(GAME_FILES):
				continue  # a game definition file, not a shelf path
			if not (shelf / mention).exists():
				found.append(finding("SHELF-DOC-FOLDER", f"{SHELF_DIR}/{name}", f"names the folder `{mention}`, which does not exist in the shelf"))
	return found


def mapped_rows(profiles: Iterable[str], aliases: Dict[str, str]) -> List[str]:
	return [aliases.get(name, name) for name in profiles]


def compare_ids(label: str, path: str, actual: List[str], wanted: List[str]) -> List[Finding]:
	found: List[Finding] = []
	duplicates = sorted({name for name in actual if actual.count(name) > 1})
	if duplicates:
		found.append(finding("FAMILY-IDS", path, f"{label}: more than one entry for {', '.join(duplicates)}"))
	missing, extra = sorted(set(wanted) - set(actual)), sorted(set(actual) - set(wanted))
	if missing:
		found.append(finding("FAMILY-IDS", path, f"{label}: missing {', '.join(missing)}"))
	if extra:
		found.append(finding("FAMILY-IDS", path, f"{label}: not a hoi4-imagegen family: {', '.join(extra)}"))
	return found


def check_family_ids(root: Path, catalog: Dict[str, Any]) -> List[Finding]:
	spec = read_json(root / FAMILY_IDS_FILE)
	wanted: List[str] = list(spec["families"])
	found: List[Finding] = []
	count = int(spec["expected_count"])
	if len(wanted) != count or len(set(wanted)) != count:
		found.append(finding("FAMILY-IDS", FAMILY_IDS_FILE, f"expected {count} distinct family ids, found {len(set(wanted))}"))
	aliases: Dict[str, str] = spec["profile_row_aliases"]
	rows = list(read_json(root / PROFILES_FILE)["profiles"])
	found += compare_ids("profiles.json rows", PROFILES_FILE, mapped_rows(rows, aliases), wanted)
	shelf_aliases: Dict[str, str] = spec["shelf_family_aliases"]
	without = list(spec["families_without_shelf"])
	shelf_ids = sorted({shelf_aliases.get(family["id"], family["id"]) for family in catalog["families"]} | set(without))
	found += compare_ids("shelf catalog", CATALOG_FILE, shelf_ids, wanted)
	catalog_ids = [family["id"] for family in catalog["families"]]
	if len(catalog_ids) != len(set(catalog_ids)):
		found.append(finding("FAMILY-IDS", CATALOG_FILE, "a family appears twice in the catalog"))
	builder_ids = [family["id"] for family in read_json(root / BUILDER_INPUT)["families"]]
	if builder_ids != catalog_ids:
		found.append(finding("FAMILY-IDS", BUILDER_INPUT, "the builder input and the catalog do not list the same families in the same order"))
	return found


def run_checks(root: Path = REPO_ROOT) -> List[Finding]:
	if not (root / CATALOG_FILE).is_file():
		return []
	catalog = read_json(root / CATALOG_FILE)
	kept = read_json(root / KEPT_FILE)
	shelf = root / SHELF_DIR
	found = check_family_ids(root, catalog)
	if not shelf.is_dir():
		return found + [finding("SHELF-MISSING", SHELF_DIR, "the shelf folder does not exist")]
	return found + check_files(shelf, catalog, kept) + check_counts(shelf, catalog, kept) + check_documents(shelf, catalog, kept) + check_doc_folders(shelf)


def write_docs(root: Path = REPO_ROOT) -> List[Tuple[str, int]]:
	catalog = read_json(root / CATALOG_FILE)
	kept = read_json(root / KEPT_FILE)
	written = []
	for name, text in (("CATALOG.md", render_catalog(catalog, kept)), ("REFERENCE_MANIFEST.md", render_manifest(catalog, kept))):
		data = text.encode("utf-8")
		(root / SHELF_DIR / name).write_bytes(data)
		written.append((name, len(data)))
	return written


def main() -> int:
	parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
	parser.add_argument("--json", type=Path, help="also write the findings as JSON")
	parser.add_argument("--write-docs", action="store_true", help="rewrite CATALOG.md and REFERENCE_MANIFEST.md from the catalog")
	add_arguments(parser)
	arguments = parser.parse_args()
	if arguments.write_docs:
		for name, size in write_docs():
			print(f"wrote {SHELF_DIR}/{name} ({size:,} bytes)")
	selector = PathFilter(requested_paths(arguments))
	findings = sorted((f for f in run_checks() if selector.matches(f.path)), key=lambda f: (f.path, f.line, f.rule, f.message))
	print_findings(CHECK, findings)
	if arguments.json:
		merge_json(arguments.json, findings, LEVELS)
	return exit_code(findings, arguments.fail_on)


if __name__ == "__main__":
	raise SystemExit(main())
