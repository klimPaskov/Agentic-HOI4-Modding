from __future__ import annotations

import json
import hashlib
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / ".tools" / "image_generation" / "providers" / "gptimage"))
import bootstrap as bootstrap_gptimage


class GptimageBootstrapTests(unittest.TestCase):
    def setUp(self) -> None:
        resolver = mock.patch.object(bootstrap_gptimage, "npm_command", return_value=["C:/node/node.exe", "C:/node/npm-cli.js"])
        resolver.start()
        self.addCleanup(resolver.stop)

    def make_package(self, root: Path) -> Path:
        package = root / "gptimage"
        (package / "src").mkdir(parents=True)
        (package / "package.json").write_text(json.dumps({"name": "gptimage", "version": "0.1.0"}), encoding="utf-8")
        (package / "package-lock.json").write_text("{}\n", encoding="utf-8")
        (package / "src" / "server.js").write_text("server\n", encoding="utf-8")
        return package

    def test_uses_frozen_lock_and_removes_temporary_npm_cache(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            package = self.make_package(Path(directory))
            calls = []

            def fake_run(args, **kwargs):
                calls.append((args, kwargs))
                cache = Path(args[args.index("--cache") + 1])
                user_config = Path(args[args.index("--userconfig") + 1])
                global_config = Path(args[args.index("--globalconfig") + 1])
                # npm refuses to load one file as both configuration scopes.
                self.assertNotEqual(user_config.resolve(), global_config.resolve())
                for config in (user_config, global_config):
                    self.assertEqual(config.parent, cache)
                    self.assertEqual(config.read_bytes(), b"")
                (package / "node_modules" / "@modelcontextprotocol" / "sdk").mkdir(parents=True)
                (package / "node_modules" / "@modelcontextprotocol" / "sdk" / "package.json").write_text("{}", encoding="utf-8")
                self.assertTrue(cache.is_dir())
                return SimpleNamespace(returncode=0, stdout="", stderr="")

            result = bootstrap_gptimage.install(
                package,
                fake_run,
                expected_tree_sha256=bootstrap_gptimage.source_tree_sha256(package),
                expected_lock_sha256=hashlib.sha256(bootstrap_gptimage.source_bytes(package / "package-lock.json")).hexdigest(),
            )
            self.assertEqual(result, {"status": "ready", "package": "gptimage", "version": "0.1.0"})
            args, kwargs = calls[0]
            self.assertEqual(args[:3], ["C:/node/node.exe", "C:/node/npm-cli.js", "ci"])
            self.assertIn("--ignore-scripts", args)
            self.assertIn("--no-bin-links", args)
            self.assertIn("--no-audit", args)
            self.assertNotIn("shell", kwargs)
            self.assertFalse(Path(args[args.index("--cache") + 1]).exists())

    def test_source_pin_is_stable_for_windows_and_unix_text_line_endings(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            package = self.make_package(Path(directory))
            expected_tree = bootstrap_gptimage.source_tree_sha256(package)
            expected_lock = hashlib.sha256(bootstrap_gptimage.source_bytes(package / "package-lock.json")).hexdigest()
            for path in package.rglob("*"):
                if path.is_file() and path.suffix in {".json", ".js"}:
                    contents = path.read_bytes().replace(b"\r\n", b"\n")
                    path.write_bytes(contents.replace(b"\n", b"\r\n"))
            self.assertEqual(bootstrap_gptimage.source_tree_sha256(package), expected_tree)
            self.assertEqual(
                hashlib.sha256(bootstrap_gptimage.source_bytes(package / "package-lock.json")).hexdigest(),
                expected_lock,
            )
            cache = package / "__pycache__"
            cache.mkdir()
            (cache / "bootstrap.pyc").write_bytes(b"generated bytecode")
            self.assertEqual(bootstrap_gptimage.source_tree_sha256(package), expected_tree)

    def test_rejects_an_unexpected_package_before_running_npm(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            package = self.make_package(Path(directory))
            (package / "package.json").write_text(json.dumps({"name": "other", "version": "0.1.0"}), encoding="utf-8")
            called = False

            def fake_run(*args, **kwargs):
                nonlocal called
                called = True
                return SimpleNamespace(returncode=0, stdout="", stderr="")

            with self.assertRaisesRegex(RuntimeError, "does not match"):
                bootstrap_gptimage.install(package, fake_run)
            self.assertFalse(called)

    def test_rejects_changed_source_and_lockfile_before_running_npm(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            package = self.make_package(Path(directory))
            expected_tree = bootstrap_gptimage.source_tree_sha256(package)
            expected_lock = hashlib.sha256(bootstrap_gptimage.source_bytes(package / "package-lock.json")).hexdigest()
            (package / "src" / "server.js").write_text("changed\n", encoding="utf-8")
            called = False

            def fake_run(*args, **kwargs):
                nonlocal called
                called = True
                return SimpleNamespace(returncode=0, stdout="", stderr="")

            with self.assertRaisesRegex(RuntimeError, "source tree"):
                bootstrap_gptimage.install(package, fake_run, expected_tree_sha256=expected_tree)
            self.assertFalse(called)
            (package / "src" / "server.js").write_text("server\n", encoding="utf-8")
            (package / "package-lock.json").write_text("changed\n", encoding="utf-8")
            with self.assertRaisesRegex(RuntimeError, "lockfile"):
                bootstrap_gptimage.install(package, fake_run, expected_lock_sha256=expected_lock)
            self.assertFalse(called)

    def test_install_errors_do_not_return_dependency_output(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            package = self.make_package(Path(directory))

            def fake_run(*args, **kwargs):
                return SimpleNamespace(returncode=1, stdout="private output", stderr="token=private-value")

            with self.assertRaisesRegex(RuntimeError, "could not be installed") as error:
                bootstrap_gptimage.install(package, fake_run)
            self.assertNotIn("private-value", str(error.exception))

    def test_missing_npm_is_reported_before_installation(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            package = self.make_package(Path(directory))
            run = mock.Mock()
            with mock.patch.object(bootstrap_gptimage, "npm_command", side_effect=RuntimeError("Node.js LTS and npm are required")):
                with self.assertRaisesRegex(RuntimeError, "Node.js LTS and npm"):
                    bootstrap_gptimage.install(package, run)
            run.assert_not_called()

    def test_npm_entry_is_run_directly_from_paths_with_shell_characters(self) -> None:
        with tempfile.TemporaryDirectory(prefix="gptimage & ") as directory:
            root = Path(directory)
            node = root / "node.exe"
            npm = root / "npm.cmd"
            cli = root / "node_modules/npm/bin/npm-cli.js"
            cli.parent.mkdir(parents=True)
            for path in (node, npm, cli):
                path.write_bytes(b"fixture")
            # Stop the per-test fixture override for this resolver-only case.
            import importlib.util
            spec = importlib.util.spec_from_file_location("gptimage_resolver", Path(bootstrap_gptimage.__file__))
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            with mock.patch.object(module.shutil, "which", side_effect=[str(node), str(npm)]):
                self.assertEqual(module.npm_command(), [str(node.resolve()), str(cli.resolve())])


if __name__ == "__main__":
    unittest.main()
